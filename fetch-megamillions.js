/**
 * fetch-megamillions.js — EurekaLott
 * Tải Mega Millions draws từ Texas Lottery CSV chính thức
 * RAW ORDER — không sort
 * Output: megamillions-data.js (browser-compatible, không có module.exports)
 *
 * ⚠️ Format CSV (xác minh trực tiếp từ trang download chính thức của
 * texaslottery.com — KHÔNG đoán mò URL, tránh lặp lại lỗi cũ):
 *   Dec 5, 2003 – Apr 4, 2025:  Game Name, Month, Day, Year, N1-5, MegaBall, Megaplier
 *   Apr 8, 2025 – nay:          Game Name, Month, Day, Year, N1-5, MegaBall   (bỏ Megaplier)
 * → Script chỉ đọc đúng 9 cột đầu tiên (index 0-9), bỏ qua Megaplier nếu có,
 *   y hệt cách fetch-draws.js đang bỏ qua "multiplier" của Powerball.
 */

const https = require('https');
const fs    = require('fs');

function get(url) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (compatible; EurekaLott-Bot/1.0)',
        'Accept': 'text/csv,*/*',
      },
      timeout: 15000,
    }, res => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return get(res.headers.location).then(resolve).catch(reject);
      }
      if (res.statusCode !== 200) {
        return reject(new Error(`HTTP ${res.statusCode}`));
      }
      let body = '';
      res.on('data', chunk => body += chunk);
      res.on('end', () => resolve(body));
    });
    req.on('error', reject);
    req.on('timeout', () => { req.destroy(); reject(new Error('Timeout')); });
  });
}

(async () => {
  console.log('\n🎲 EurekaLott — Fetching Mega Millions draws (RAW ORDER)...\n');

  const url = 'https://www.texaslottery.com/export/sites/lottery/Games/Mega_Millions/Winning_Numbers/megamillions.csv';

  let body;
  try {
    body = await get(url);
    console.log(' [B] ✅ Texas Lottery CSV fetched');
  } catch (err) {
    console.error('❌ Failed to fetch Texas CSV:', err.message);
    process.exit(1);
  }

  const draws = [];
  const lines = body.trim().split('\n');

  for (const line of lines) {
    const cols = line.trim().split(',').map(c => c.trim().replace(/"/g, ''));
    if (cols.length < 10 || cols[0] !== 'Mega Millions') continue;

    const month = cols[1].padStart(2, '0');
    const day   = cols[2].padStart(2, '0');
    const year  = cols[3];
    const date  = `${year}-${month}-${day}`;

    const w1 = parseInt(cols[4], 10);
    const w2 = parseInt(cols[5], 10);
    const w3 = parseInt(cols[6], 10);
    const w4 = parseInt(cols[7], 10);
    const w5 = parseInt(cols[8], 10);
    const mb = parseInt(cols[9], 10);

    if ([w1, w2, w3, w4, w5, mb].some(n => isNaN(n) || n < 1)) continue;

    draws.push({
      date,
      white: [w1, w2, w3, w4, w5],  // RAW ORDER — không sort
      megaball: mb,
    });
  }

  if (draws.length === 0) {
    console.error('❌ No draws parsed.');
    process.exit(1);
  }

  draws.sort((a, b) => a.date.localeCompare(b.date));

  const json = JSON.stringify(draws, null, 2);

  fs.writeFileSync('megamillions-data.js',
`// megamillions-data.js — AUTO-GENERATED by fetch-megamillions.js
// Do not edit manually.
// Source: Texas Lottery CSV (official)
// Last updated: ${new Date().toISOString()}
// ⚠️  white[] = RAW ORDER (thứ tự bóng rơi thực tế, KHÔNG sorted)

var megamillions = ${json};

// End of megamillions-data.js
`);

  console.log(`\n✅ megamillions-data.js written`);
  console.log(`   Total  : ${draws.length} draws`);
  console.log(`   Oldest : ${draws[0].date}`);
  console.log(`   Newest : ${draws[draws.length-1].date}`);
  console.log(`   Latest : white:[${draws[draws.length-1].white}] mb:${draws[draws.length-1].megaball}`);
  console.log('\n⚠️  No module.exports — browser compatible only\n');
})();
