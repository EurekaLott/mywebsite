/**
 * fetch-lottotexas.js — EurekaLott
 * Tải Lotto Texas draws từ Texas Lottery CSV chính thức
 * RAW ORDER — không sort
 * Output: lottotexas-data.js (browser-compatible, không có module.exports)
 *
 * ⚠️ Format CSV (xác minh trực tiếp từ trang download chính thức):
 *   Apr 26, 2006 – nay: Game Name, Month, Day, Year, N1, N2, N3, N4, N5, N6
 *   (6 số CÙNG 1 pool, KHÔNG có bonus ball riêng — khác Powerball/Mega Millions)
 */

const https = require('https');
const fs    = require('fs');

function get(url) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (compatible; EurekaLott-Bot/1.0)',
        'Accept': 'text/csv,*/*',
      },
      timeout: 15000,
    }, res => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return get(res.headers.location).then(resolve).catch(reject);
      }
      if (res.statusCode !== 200) {
        return reject(new Error(`HTTP ${res.statusCode}`));
      }
      let body = '';
      res.on('data', chunk => body += chunk);
      res.on('end', () => resolve(body));
    });
    req.on('error', reject);
    req.on('timeout', () => { req.destroy(); reject(new Error('Timeout')); });
  });
}

(async () => {
  console.log('\n🤠 EurekaLott — Fetching Lotto Texas draws (RAW ORDER)...\n');

  const url = 'https://www.texaslottery.com/export/sites/lottery/Games/Lotto_Texas/Winning_Numbers/lottotexas.csv';

  let body;
  try {
    body = await get(url);
    console.log(' [B] ✅ Texas Lottery CSV fetched');
  } catch (err) {
    console.error('❌ Failed to fetch Texas CSV:', err.message);
    process.exit(1);
  }

  const draws = [];
  const lines = body.trim().split('\n');

  for (const line of lines) {
    const cols = line.trim().split(',').map(c => c.trim().replace(/"/g, ''));
    if (cols.length < 10 || cols[0] !== 'Lotto Texas') continue;

    const month = cols[1].padStart(2, '0');
    const day   = cols[2].padStart(2, '0');
    const year  = cols[3];
    const date  = `${year}-${month}-${day}`;

    const nums = [cols[4], cols[5], cols[6], cols[7], cols[8], cols[9]].map(n => parseInt(n, 10));
    if (nums.some(n => isNaN(n) || n < 1)) continue;

    draws.push({
      date,
      white: nums, // 6 số CÙNG pool — RAW ORDER, không sort
    });
  }

  if (draws.length === 0) {
    console.error('❌ No draws parsed.');
    process.exit(1);
  }

  draws.sort((a, b) => a.date.localeCompare(b.date));

  const json = JSON.stringify(draws, null, 2);

  fs.writeFileSync('lottotexas-data.js',
`// lottotexas-data.js — AUTO-GENERATED by fetch-lottotexas.js
// Do not edit manually.
// Source: Texas Lottery CSV (official)
// Last updated: ${new Date().toISOString()}
// ⚠️  white[] = RAW ORDER (thứ tự bóng rơi thực tế, KHÔNG sorted)
// ⚠️  Lotto Texas KHÔNG có bonus ball riêng — cả 6 số CÙNG 1 pool (1-54)

const lottotexas = ${json};

// End of lottotexas-data.js
`);

  console.log(`\n✅ lottotexas-data.js written`);
  console.log(`   Total  : ${draws.length} draws`);
  console.log(`   Oldest : ${draws[0].date}`);
  console.log(`   Newest : ${draws[draws.length-1].date}`);
  console.log(`   Latest : white:[${draws[draws.length-1].white}]`);
  console.log('\n⚠️  No module.exports — browser compatible only\n');
})();
